"""Extract the game's 694 city centres from AreaCity ok_geo.csv.

Usage: python3 scripts/prepare-city-geography.py /path/to/ok_geo.csv
Source: AreaCity-JsSpider-StatsGov release 2025.251231.260403 (MIT).
GCJ-02 input is converted to approximate WGS-84 before routing on OSM.
"""
from pathlib import Path
import csv
import json
import math
import sys

ROOT = Path(__file__).resolve().parents[1]


def delta(lon, lat):
    x, y = lon-105, lat-35
    latitude = -100+2*x+3*y+.2*y*y+.1*x*y+.2*math.sqrt(abs(x))
    longitude = 300+x+2*y+.1*x*x+.1*x*y+.1*math.sqrt(abs(x))
    common = (20*math.sin(6*x*math.pi)+20*math.sin(2*x*math.pi))*2/3
    latitude += common+(20*math.sin(y*math.pi)+40*math.sin(y/3*math.pi))*2/3
    latitude += (160*math.sin(y/12*math.pi)+320*math.sin(y*math.pi/30))*2/3
    longitude += common+(20*math.sin(x*math.pi)+40*math.sin(x/3*math.pi))*2/3
    longitude += (150*math.sin(x/12*math.pi)+300*math.sin(x/30*math.pi))*2/3
    rad = math.radians(lat)
    magic = 1-.00669342162296594323*math.sin(rad)**2
    return (longitude*180/(6378245/math.sqrt(magic)*math.cos(rad)*math.pi),
            latitude*180/((6378245*(1-.00669342162296594323))/(magic**1.5)*math.pi))


def wgs84(pair):
    lon, lat = pair
    for _ in range(5):
        dx, dy = delta(lon, lat)
        lon, lat = pair[0]-dx, pair[1]-dy
    return [round(lon, 6), round(lat, 6)]


csv.field_size_limit(50*1024*1024)
text = (ROOT/'lib/city-cities.mjs').read_text()
cities = json.loads(text[text.index('['):text.index('] .map')+1])
rows = {}
with open(sys.argv[1], encoding='utf-8-sig') as source:
    for row in csv.DictReader(source):
        key = row['ext_path'].split(' ')[0]+'|'+row['name']
        if key not in rows or int(row['deep']) < int(rows[key]['deep']):
            rows[key] = row
output = {}
for city in cities:
    key = city['province']+'|'+city['name']
    row = rows[key]
    output[key] = wgs84([float(v) for v in row['geo'].split()])
(ROOT/'lib/city-coordinates.mjs').write_text(
    '// Generated by scripts/prepare-city-geography.py; WGS-84 city centres.\n'
    '// AreaCity 2025.251231.260403; attribution: data-sources/city-geography.txt\n'
    'export const CITY_COORDINATES=Object.freeze('+json.dumps(output, ensure_ascii=False, separators=(',', ':'))+');\n')
print(json.dumps({'cities': len(output), 'beijing': output['北京市|北京市'], 'shanghai': output['上海市|上海市']}))
